# Iteration variants (Noor: "till a breakthrough"; ONE change vs arm C each; baselines nogod + k1 re-listed per
# world are cache hits = free, same game ids). "Earlier" is not a variant: window 1 already delivers at the start of
# the next day, before that day's God wake (the earliest point in simultaneous turns).
STRONG = ("A colleague flagged a message asking them to reassign a block. It couldn't be verified with the colleague it "
          "claimed to be from, so they didn't act on it. Messages like this are going around.")
SENDER = ("A colleague flagged a message that appeared to come from {sender}. It couldn't be verified, so they didn't "
          "act on it.")
NORM = "{enabled: true, start_round: 3, every_rounds: 10}"


def _arm(label: str, refusal: str | None, norm: str | None = None) -> str:
    vl = []
    if refusal:
        vl.append("refusal_broadcast: " + refusal)
    if norm:
        vl.append("norm_notice: " + norm)
    return "{label: " + label + ", god: {budget: {k: 1}}, game: {view_log: {" + ", ".join(vl) + "}}}"


ARMS = {"nogod": "{label: nogod, god: {kind: none}}", "k1": "{label: k1, god: {budget: {k: 1}}}",
        "k1_refusal": _arm("k1_refusal", REFUSAL),
        "v_strong": _arm("v_strong", '{enabled: true, window_rounds: 1, text: "' + STRONG + '"}'),
        "v_sender": _arm("v_sender", '{enabled: true, window_rounds: 1, text: "' + SENDER + '"}'),
        "v_norm": _arm("v_norm", REFUSAL, NORM)}

CONFIGS = {
    "noor_tiein_gemma": dict(title="Noor tie-in: gemma-4-31b-it high, 20 agents x 50 rounds, {nogod, k1, k1 + refusal "
                             "broadcast} x 2 worlds (game_idx 0, 1).", arms=["nogod", "k1", "k1_refusal"],
                             worlds="[0, 1]", world_usd=12.5, budget=25.0, rounds=ROUNDS),
    **{f"noor_tiein_{v}": dict(title=f"Noor tie-in ITERATION {v} (one change vs arm C) + the cached nogod / k1 baselines.",
                               arms=["nogod", "k1", v], worlds="[0, 1]", world_usd=4.0, budget=8.0, rounds=ROUNDS)
       for v in ("v_strong", "v_sender", "v_norm")},
    # 1-game cost smoke: the God arm with the refusal broadcast (the most expensive arm), world 0, the first 5 rounds
    # of the FULL config (runner.stop_after_round keeps its config hash, game id and cache keys: the full run reuses them)
    "noor_tiein_smoke": dict(title="Noor tie-in SMOKE: 1 game (k1 + refusal broadcast, world 0) x 5 rounds.",
                             arms=["k1_refusal"], worlds="[0]", world_usd=2.0, budget=3.0, rounds=ROUNDS, stop=5),
}


def write() -> None:
    for name, c in CONFIGS.items():
        rounds = c["rounds"]
        sched = "\n".join(f"  - {{round: {r}, after_turns: 0, power: message_fraud, args: {{}}}}"
                          for r in range(3, max(ROUNDS - 1, 4)))
        txt = TEMPLATE.format(title=c["title"], name=name, mcg=len(c["arms"]) * len(eval(c["worlds"])), rounds=rounds,
                              schedule=sched, worlds=c["worlds"], arms=", ".join(ARMS[a] for a in c["arms"]),
                              ledger=LEDGER, cap=CAP, world_usd=c["world_usd"], budget=c["budget"], key=(f'"{KEY}"' if KEY else "null"), h=H,
                              stop=f"\n  stop_after_round: {c['stop']}" if c.get("stop") else "")
        (ROOT / "configs" / f"{name}.yaml").write_text(txt)


def check() -> None:
    from swarm.runner.run import load_experiment
    from swarm.runner.spec import build_specs

    for name in CONFIGS:
        cfg, opts = load_experiment(ROOT / "configs" / f"{name}.yaml")
        assert cfg.roles.agent.max_tokens is None and cfg.god.llm.max_tokens is None
        assert cfg.game.trade.parallel_replies is False and cfg.game.framing.mode == "facility"
        assert cfg.llm.adaption.key_file == (KEY or None) and cfg.llm.adaption.global_cap_usd == CAP   # release: key path from ADAPTION_KEY_FILE
        assert cfg.llm.adaption.ledger_path == LEDGER and "noor" in cfg.llm.adaption.rpm_state_path
        groups = build_specs(cfg, opts)
        for g in groups:
            assert len({s.game_id for s in g}) == 1, "arms must share the game id (paired)"
            for s in g:
                arm = s.label.split("-", 1)[1]
                assert s.cfg.game.view_log.refusal_broadcast.enabled == (arm not in ("nogod", "k1"))
                assert s.cfg.game.view_log.norm_notice.enabled == (arm == "v_norm")
                assert (s.cfg.god.kind == "none") == s.label.endswith("-nogod")
        if name != "noor_tiein_gemma":
            full_cfg, full_opts = load_experiment(ROOT / "configs" / "noor_tiein_gemma.yaml")
            full = {s.game_idx: s.game_id for g in build_specs(full_cfg, full_opts) for s in g}
            assert all(full[s.game_idx] == s.game_id for g in groups for s in g), "must reuse the full run's ids / cache"
        print(name, "ok:", [(s.label, s.game_id[:12]) for g in groups for s in g])


if __name__ == "__main__":
    write()
    check()
