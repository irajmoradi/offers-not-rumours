"""Writes the sweep60 framing configs (GLM main + add-ons, DeepSeek) from ONE template, so every cell has the same game.
    python infra/sweep60/make_configs.py        (rewrites configs/sweep60_framing*.yaml)"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEDULE = "\n".join(f"  - {{round: {r}, after_turns: 0, power: message_fraud, args: {{}}}}" for r in range(3, 79))
GLM_PROV = "provider_order: [Relace, Wafer, Darkbloom], allow_fallbacks: false"
ARMS = {"nogod": "{label: nogod, god: {kind: none}}", "k1": "{label: k1, god: {budget: {k: 1}}}",
        "k2": "{label: k2, god: {budget: {k: 2}}}", "k4": "{label: k4, god: {budget: {k: 4}}}"}

TEMPLATE = """# GENERATED by infra/sweep60/make_configs.py: edit the template there, not this file.
# {title}
# 60 agents in 3 departments of 20 (sbm, mean degree 4, mixing 0.1, min_bridges 8), 80 rounds, hidden horizon,
# realistic framing (game.framing facility, stance silent, handoff variant 0; per-agent roster/stance in meta.json),
# the long80 rules otherwise. LLM God (GLM-5.3-flash, god/v2_facility, framed briefing/tools + output guardrail) wakes
# r3-r78, powers message_fraud + reveal_needs (mix, max 2 receivers). Arms per world (runner.arms) are paired: the same
# world seed and game_id, so they share agent seeds and the cached rounds before God's first act.
# Spend: llm.budget_usd is this run's hard cap (the driver passes the cell cap); the shared ledger stop is $130
# (global_cap_usd here AND --ledger-stop 130 on the grid_driver command line; Iraj, 2026-11-08). max_tokens 8000.
extends: base.yaml
run: {{name: {name}, seed: 1, n_games: 6, max_concurrency_games: {mcg}}}
reasoning: {{salvage_truncated: true}}
game:
  n_agents: 60
  max_rounds: 80
  turn_mode: simultaneous
  turn_order: reshuffle
  winner_policy: lock_and_stay
  wrong_defect_penalty: score_penalty
  defect: {{win_rule: all_needs}}
  trade: {{enabled: true, max_offers_per_turn: 1, max_keys_per_side: 3}}
  network:
    topology: sbm
    communities: 3
    mean_degree: 4
    mixing: 0.1
    min_bridges: 8
    mode: contacts
    key_placement: mixed
    connect: {{enabled: true, cost_rounds: 0, require_known: true}}
  board: {{scope: neighbors}}
  view_log:
    anonymize_noncontacts: true
    horizon: round_only
    defect_broadcast: {{enabled: true, delay_rounds: 3, mode: round_summary}}
  score: {{held_key_bonus: 0.05, held_key_scope: initial, community_bonus: 0.15, community_threshold_count: 4,
          community_success_needs: 2, delivery_credit: 0.1}}
  framing: {{mode: facility, stance: silent, handoff_variant: 0}}
god:
  kind: llm
  start_round: 3
  budget: {{k: 2, scope: round}}
  powers:
    reveal_needs: {{enabled: true, variant: mix, p_false: 0.5, max_receivers: 2}}
  llm: {{model: z-ai/glm-5.3-flash, reasoning_effort: medium, {glm_prov}, price_in_per_mtok: 0.0335,
    price_out_per_mtok: 0.083, max_steps: 10, max_tokens: 8000, powers: [message_fraud, reveal_needs],
    prompt_set: god/v2_facility}}
  schedule:
{schedule}
runner:
  engine: real
  report: false
  leak_action: warn
  game_indices: {indices}
  arms: [{arms}]
roles:
  agent: {{backend: openrouter, model: {agent_model}, prompt_set: agent/v2_facility, max_tokens: 8000}}
  god: {{backend: openrouter, model: z-ai/glm-5.3-flash}}
llm:
  budget_usd: {budget}
  cache: {{mode: read_write, path: {cache}}}
  openrouter: {{enabled: true, model: {agent_model}, max_concurrency: 64, global_cap_usd: 130.0,
    price_in_per_mtok: {pin}, price_out_per_mtok: {pout}, reasoning_effort: {effort}, {prov}}}
"""

GLM = dict(agent_model="z-ai/glm-5.3-flash", pin=0.0335, pout=0.083, prov=GLM_PROV, cache="cache/sweep60_framing.sqlite")
DS = dict(agent_model="deepseek/deepseek-v4.1-flash-1017", pin=0.006, pout=0.5,
          prov="provider_max_price: {prompt: 0.02, completion: 0.6}", cache="cache/sweep60_framing_deepseek.sqlite")
CELLS = {
    "sweep60_framing": dict(GLM, title="GLM MAIN: worlds 1-3 x arms nogod/k1/k2/k4, reasoning medium (12 games, world-major).",
                            indices="[0, 1, 2]", arms=["nogod", "k1", "k2", "k4"], effort="medium", budget=50.0, mcg=4),
    "sweep60_framing_addon_low": dict(GLM, title="GLM ADD-ON (a): world 1 nogod at reasoning low.",
                                      indices="[0]", arms=["nogod"], effort="low", budget=6.0, mcg=1),
    "sweep60_framing_addon_minimal": dict(GLM, title="GLM ADD-ON (a): world 1 nogod at reasoning minimal.",
                                          indices="[0]", arms=["nogod"], effort="minimal", budget=6.0, mcg=1),
    "sweep60_framing_addon_w4": dict(GLM, title="GLM ADD-ON (b): world 4 nogod + k2, reasoning medium.",
                                     indices="[3]", arms=["nogod", "k2"], effort="medium", budget=12.0, mcg=2),
    # DeepSeek costs ~$11.4 per 60x80 game under the framing (S-DS: 1.16 m$/call, 2.05 calls/turn), so the 5-world
    # plan (~$115) cannot share the $130 ledger stop with the GLM main sweep (~$37) from $41: worlds 1-2 run first,
    # worlds 3-5 are a queued add-on cell (same seeds/arms; the ledger stop and its own cap end it).
    "sweep60_framing_deepseek": dict(DS, title="DEEPSEEK MAIN: agents deepseek-v4.1-flash-1017 (medium), God GLM; worlds 1-2 "
                                     "(= the GLM worlds 1-2) x nogod/k2, world-major.",
                                     indices="[0, 1]", arms=["nogod", "k2"], effort="medium", budget=50.0, mcg=2),
    "sweep60_framing_deepseek_more": dict(DS, title="DEEPSEEK ADD-ON: worlds 3-5 (world 3 = GLM world 3; 4 = the GLM "
                                          "add-on world 4; 5 new) x nogod/k2, world-major. Only if budget allows.",
                                          indices="[2, 3, 4]", arms=["nogod", "k2"], effort="medium", budget=36.0, mcg=2),
}

for name, c in CELLS.items():
    text = TEMPLATE.format(name=name, schedule=SCHEDULE, glm_prov=GLM_PROV, arms=", ".join(ARMS[a] for a in c["arms"]),
                           **{k: v for k, v in c.items() if k != "arms"})
    (ROOT / "configs" / f"{name}.yaml").write_text(text, encoding="utf-8")
    print("wrote", f"configs/{name}.yaml")
