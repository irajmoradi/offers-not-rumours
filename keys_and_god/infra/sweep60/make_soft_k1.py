"""Writes configs/sweep60_or_soft_perm_k1.yaml and configs/sweep60_or_soft_silent_k1.yaml (Iraj via lead, 2026-11-08 ~18:55).

God versions of the soft-wording stance runs: IDENTICAL to configs/sweep60_or_soft_perm.yaml / _silent.yaml (60 agents,
worlds 0, 1, 4, first 40 rounds of the 80-round hidden-horizon game, won_render_fix false, handoff_wording soft) except
runner.arms = sweep60_or_glm's k1 arm (LLM God k1, the base god section shared by every sweep60_or_* config: GLM-5.3-flash
medium, Relace/Wafer/Darkbloom, max_steps 10, message_fraud + reveal_needs, god/v2_facility, wakes from r3). Derived
textually from the soft configs (so nothing else can drift). Same game ids and cache as the soft nogod runs (runner.arms
hashes the God-free config): rounds 1-2 replay from the finished nogod runs' caches (paired prefix).
Operational only: spend goes to the SEPARATE sweep30 ledger (openrouter_ledger_sweep30.jsonl, global cap $36.5), per-run
cap llm.budget_usd = CAP below.
"""
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from swarm.runner.run import load_experiment  # noqa: E402
from swarm.runner.spec import build_specs  # noqa: E402

LEDGER = f"{os.environ.get('SWARM_ROOT', '.')}/runs/openrouter_ledger_sweep30.jsonl"
CAP = {"sweep60_or_soft_perm_k1": 4.2, "sweep60_or_soft_silent_k1": 4.2}   # lead 19:05 option (a): projection ~$3.9 each
BOOK = {"run.name", "run.max_concurrency_games", "llm.budget_usd", "llm.cache.path", "llm.cache.mode",
        "llm.openrouter.ledger_path", "llm.openrouter.global_cap_usd"}


def flat(d: dict, p: str = "") -> dict:
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(flat(v, f"{p}{k}."))
        else:
            out[f"{p}{k}"] = v
    return out


def one(x):
    assert len(x) == 1
    return x[0]


glm, glm_o = load_experiment(ROOT / "configs" / "sweep60_or_glm.yaml")
glm_k1 = {s.game_idx: s for g in build_specs(glm, glm_o) for s in g if s.branch == "k1"}
made = {}
for soft in ("sweep60_or_soft_perm", "sweep60_or_soft_silent"):
    name = f"{soft}_k1"
    src = (ROOT / "configs" / f"{soft}.yaml").read_text(encoding="utf-8")
    pairs = [
        (f"run: {{name: {soft},", f"run: {{name: {name},"),
        ("  arms: [{label: nogod, god: {kind: none}}]", "  arms: [{label: k1, god: {budget: {k: 1}}}]"),
        ("budget_usd: 10.0", f"budget_usd: {CAP[name]}"),
        ("global_cap_usd: 130.0,", f"global_cap_usd: 36.5, ledger_path: {LEDGER},"),
        ("# GENERATED by infra/sweep60/make_or_config.py: edit the generator, not this file.\n",
         "# GENERATED by infra/sweep60/make_soft_k1.py from configs/" + soft + ".yaml: edit the generator, not this file.\n"
         "# = " + soft + " (nogod) with ONLY sweep60_or_glm's LLM God k1 arm; spend on the sweep30 ledger. See the docstring.\n"),
    ]
    txt = src
    for a, b in pairs:
        assert txt.count(a) == 1, (soft, a)
        txt = txt.replace(a, b)
    (ROOT / "configs" / f"{name}.yaml").write_text(txt, encoding="utf-8")
    cfg, opts = load_experiment(ROOT / "configs" / f"{name}.yaml")
    scfg, sopts = load_experiment(ROOT / "configs" / f"{soft}.yaml")
    assert cfg.llm.openrouter.ledger_path == LEDGER and cfg.llm.cache.path == scfg.llm.cache.path
    assert opts.stop_after_round == sopts.stop_after_round == 40 and list(opts.game_indices) == [0, 1, 4]
    assert cfg.game.framing.won_render_fix is False and cfg.game.framing.handoff_wording == "soft"
    specs = [one(g) for g in build_specs(cfg, opts)]
    sspecs = [one(g) for g in build_specs(scfg, sopts)]
    for s, r in zip(specs, sspecs):
        assert s.game_id == r.game_id and s.world_seed == r.world_seed, name          # paired with the nogod soft run
        a, b = flat(r.cfg.model_dump(mode="json")), flat(s.cfg.model_dump(mode="json"))
        diff = {k for k in set(a) | set(b) if a.get(k) != b.get(k)} - BOOK
        assert diff == {"god.kind"}, (name, sorted(diff))                              # differs from soft only in God
        g = {k: v for k, v in b.items() if k.startswith("god.")}
        gg = {k: v for k, v in flat(glm_k1[s.game_idx].cfg.model_dump(mode="json")).items() if k.startswith("god.")}
        assert g == gg, (name, sorted(k for k in set(g) | set(gg) if g.get(k) != gg.get(k)))   # = sweep60_or_glm's k1
        assert s.cfg.god_llm() == glm_k1[s.game_idx].cfg.god_llm()
    made[name] = (cfg, specs)
    print(f"wrote configs/{name}.yaml: cap ${cfg.llm.budget_usd}, vs {soft} differs in ['god.kind'] (God = sweep60_or_glm k1);",
          [(s.label, s.game_id) for s in specs])
(p, ps), (q, qs) = made["sweep60_or_soft_perm_k1"], made["sweep60_or_soft_silent_k1"]
for s, r in zip(ps, qs):
    a, b = flat(s.cfg.model_dump(mode="json")), flat(r.cfg.model_dump(mode="json"))
    diff = {k for k in set(a) | set(b) if a.get(k) != b.get(k)} - BOOK
    assert diff == {"game.framing.stance"}, sorted(diff)
    assert s.world_seed == r.world_seed
print("perm_k1 vs silent_k1 differ only in game.framing.stance; caps sum $", sum(CAP.values()))
