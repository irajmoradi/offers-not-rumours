    c5, o5 = load_experiment(ROOT / "configs" / f"{name}.yaml")
    a, b = flat(cfg.model_dump(mode="json")), flat(c5.model_dump(mode="json"))
    diff = {k for k in set(a) | set(b) if a.get(k) != b.get(k)} - BOOK
    base = name.removesuffix("_x")
    want = expect.get(base, {"sweep60_or_oldframe": {"game.framing", "roles.agent.prompt_set", "god.llm.prompt_set"},
                             "sweep60_or_c2_maxtok": {"roles.agent.max_tokens"}}.get(base))
    assert diff == want, (name, sorted(diff))
