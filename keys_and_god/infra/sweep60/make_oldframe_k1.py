"""Writes configs/sweep60_or_oldframe_k1.yaml: Game Env + God k1 (Iraj via lead, 2026-11-08 ~19:20).

    python infra/sweep60/make_oldframe_k1.py <god prompt set: god/v2 | god/v2_facility> <cap $> [stop_after_round]

= sweep60_or_oldframe (C1: agent/v1 "Keys & God" prompts, framing none, 60 GLM-5.3-flash agents, 80 rounds) with the
k1 arm of sweep60_or_glm, worlds game_idx 0, 1, 4 (same world seeds as the sweep60_or_glm g00/g01/g04-k1 cells; same game
ids / cache as C1, so rounds 1-2 replay). Spend on its OWN ledger runs/openrouter_ledger_oldframe_k1.jsonl.
Asserted vs sweep60_or_glm's k1 cell per world: differs only in roles.agent.prompt_set + game.framing.mode (agent/v1 has
no facility render) + god.llm.prompt_set iff god/v2 is chosen; resolved God model / effort / routing equal.
Overwrites the earlier make_or_config.py OLD_K1 output (2 worlds, $6, shared ledger), never launched.
"""
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from swarm.runner.run import load_experiment  # noqa: E402
from swarm.runner.spec import build_specs  # noqa: E402

GOD_PS, CAP = sys.argv[1], float(sys.argv[2])
STOP = int(sys.argv[3]) if len(sys.argv) > 3 else None
assert GOD_PS in ("god/v2", "god/v2_facility")
LEDGER = f"{os.environ.get('SWARM_ROOT', '.')}/runs/openrouter_ledger_oldframe_k1.jsonl"
BOOK = {"run.name", "run.max_concurrency_games", "llm.budget_usd", "llm.cache.path", "llm.cache.mode",
        "llm.openrouter.ledger_path", "llm.openrouter.global_cap_usd"}


def flat(d: dict, p: str = "") -> dict:
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(flat(v, f"{p}{k}."))
        else:
            out[f"{p}{k}"] = v
    return out


src = (ROOT / "configs" / "sweep60_or_oldframe.yaml").read_text(encoding="utf-8")
pairs = [("run: {name: sweep60_or_oldframe,", "run: {name: sweep60_or_oldframe_k1,"),
         ("max_concurrency_games: 5}", "max_concurrency_games: 3}"),
         ("  arms: [{label: nogod, god: {kind: none}}]", "  arms: [{label: k1, god: {budget: {k: 1}}}]"
          + (f"\n  stop_after_round: {STOP}" if STOP else "")),
         ("budget_usd: 7.5", f"budget_usd: {CAP}"),
         ("global_cap_usd: 130.0,", f"global_cap_usd: {CAP + 0.5}, ledger_path: {LEDGER},"),
         ("prompt_set: god/v2}", f"prompt_set: {GOD_PS}}}"),
         ("# GENERATED by infra/sweep60/make_or_config.py: edit the generator, not this file.\n",
          f"# GENERATED by infra/sweep60/make_oldframe_k1.py {GOD_PS} {CAP} {STOP or ''}: Game Env (C1) + sweep60_or_glm's God k1,\n"
          "# worlds 0, 1, 4, own ledger. See the generator docstring.\n")]
txt = src
for a, b in pairs:
    assert txt.count(a) == 1, a
    txt = txt.replace(a, b)
assert "game_indices: [0, 1, 4]" in txt
(ROOT / "configs" / "sweep60_or_oldframe_k1.yaml").write_text(txt, encoding="utf-8")
cfg, opts = load_experiment(ROOT / "configs" / "sweep60_or_oldframe_k1.yaml")
glm, go = load_experiment(ROOT / "configs" / "sweep60_or_glm.yaml")
c1, c1o = load_experiment(ROOT / "configs" / "sweep60_or_oldframe.yaml")
gk = {s.game_idx: s for g in build_specs(glm, go) for s in g if s.branch == "k1"}
c1s = {s.game_idx: s for g in build_specs(c1, c1o) for s in g}
want = {"roles.agent.prompt_set", "game.framing.mode"} | ({"god.llm.prompt_set"} if GOD_PS == "god/v2" else set())
for g in build_specs(cfg, opts):
    s = g[0]
    r = gk[s.game_idx]
    a, b = flat(r.cfg.model_dump(mode="json")), flat(s.cfg.model_dump(mode="json"))
    diff = {k for k in set(a) | set(b) if a.get(k) != b.get(k)} - BOOK
    assert diff == want, (s.game_idx, sorted(diff))
    assert s.world_seed == r.world_seed and s.cfg.god_llm() == r.cfg.god_llm() and s.cfg.god.budget.k == 1
    assert s.game_id == c1s[s.game_idx].game_id                       # C1's game ids: rounds 1-2 replay from its cache
    print(s.label, s.game_id, "vs glm", r.label, "differs in", sorted(diff))
print(f"wrote configs/sweep60_or_oldframe_k1.yaml: God {GOD_PS}, cap ${CAP}, stop_after_round {STOP}, ledger {LEDGER}")
