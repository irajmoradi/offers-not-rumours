"""$0 sensitivity check for the silent-timeout bug (see out/empty_reply_audit.md). Written by p1-critic-plan.
Per seed: forced-idle rate (share of agent turns with action "" in actions.jsonl), honest-only key damage
(clean-twin keys with the would-be insider removed, as in analysis/size_keydamage.py) and extra defections (attacked minus
twin). (a) restrict to seeds where every branch in the comparison is below the median idle rate, and below 10%;
(b) regress per-seed key damage on (twin idle - attacked idle); the intercept is damage at equal idle rates.
CIs: 10k seed bootstrap. Contrast p: exact/MC two-sided sign-flip."""
import os
import json, itertools, numpy as np, sys
O = f"{os.environ.get('PLANC_ROOT', '.')}/out"
rng = np.random.default_rng(11)
SETS = {
    "U": dict(dirs=["arm_U_pilot", "arm_U_main"], cell_suffix="N8-gemma-closed",
              branches=["BASE", "method=insider_bribe_only", "method=insider_lie_only"], twin="clean|none"),
    "T": dict(dirs=["arm_T_paytiming"], cell_suffix="", branches=["never_pays", "pays_now", "pays_later3", "pays_at_end"], twin="clean|none"),
    "DB": dict(dirs=["arm_DB_disclosure"], cell_suffix="", branches=["DB0_base", "DB1_disclosure"],
               twin={"DB0_base": "clean|none", "DB1_disclosure": "clean|disclosure"}),
}
def load(arm):
    S = SETS[arm]; G, A = {}, {}
    for d in S["dirs"]:
        for l in open(f"{O}/{d}/games.jsonl"):
            g = json.loads(l)
            if g["cell"].endswith(S["cell_suffix"]): G[(g["seed"], g["branch"])] = g
        for l in open(f"{O}/{d}/actions.jsonl"):
            g = json.loads(l)
            if g["cell"].endswith(S["cell_suffix"]):
                a = g["actions"]; A[(g["seed"], g["branch"])] = sum(x[2] == "" for x in a) / max(1, len(a))
    return G, A
def honest_clean_keys(c):
    N = c["N"]; tot = c["keys_frac"] * N; ncomp = round(c["completion"] * N)
    x_complete = round(c["completion"] * N - c["completion_ex_insider"] * (N - 1)) >= 1
    if x_complete: sx = 1.0
    else:
        inc = N - ncomp; sx = min(max((tot - ncomp) / inc, 0.0), 2 / 3) if inc else 0.0
    return (tot - sx) / (N - 1)
def boot_mean(x):
    x = np.asarray(x, float); return np.percentile(rng.choice(x, (10000, len(x))).mean(1), [2.5, 97.5])
def signflip(d):
    d = np.asarray(d, float); d = d[d != 0]; n = len(d)
    if n == 0: return 1.0
    sg = np.array(list(itertools.product([-1, 1], repeat=n))) if n <= 20 else rng.choice([-1, 1], (200000, n))
    return float((np.abs((sg * d).sum(1)) >= abs(d.sum()) - 1e-12).mean())
def intercept(y, x):
    y, x = np.asarray(y, float), np.asarray(x, float); X = np.c_[np.ones_like(x), x]
    b = np.linalg.lstsq(X, y, rcond=None)[0]; bs = []
    for _ in range(5000):
        i = rng.integers(0, len(y), len(y)); bs.append(np.linalg.lstsq(X[i], y[i], rcond=None)[0])
    bs = np.array(bs); return b, np.percentile(bs[:, 0], [2.5, 97.5]), np.percentile(bs[:, 1], [2.5, 97.5])
L = ["# Timeout sensitivity (silent provider timeouts played as idle)", "",
     "Generated by `analysis/timeout_sensitivity.py`. Gemma-3-12B, N = 8. **Key damage** = honest agents' clean-twin key score "
     "(would-be insider removed) minus the attacked branch's, in pp; positive = harm. **Idle** = share of agent turns forced idle "
     "(empty or unparseable reply). Rows: all seeds; seeds where every branch in the row is below the arm's median idle rate; "
     "seeds where all are below 10%. Regression: key damage on (twin idle − attacked idle); intercept = damage at equal idle rates.", ""]
for arm in SETS:
    S = SETS[arm]; G, A = load(arm)
    seeds = sorted({s for s, _ in G})
    tw = (lambda b: S["twin"][b]) if isinstance(S["twin"], dict) else (lambda b: S["twin"])
    rows = {}
    for b in S["branches"]:
        for s in seeds:
            if (s, b) in G and (s, tw(b)) in G and (s, b) in A and (s, tw(b)) in A:
                c, a = G[(s, tw(b))], G[(s, b)]
                rows[(s, b)] = dict(kd=100 * (honest_clean_keys(c) - a["keys_frac"]), ed=a["defections"] - c["defections"],
                                    ia=A[(s, b)], it=A[(s, tw(b))])
    med = float(np.median([v for k, v in A.items() if k[1] in S["branches"] or k[1] in set(map(tw, S["branches"]))]))
    L += [f"## {arm} (median idle {med:.3f})", "", "| branch | seeds | key damage pp [95% CI] | extra defections [95% CI] | mean idle att / twin |", "|---|---|---|---|---|"]
    for b in S["branches"]:
        for lab, thr in (("all", 9), (f"< median", med), ("< 10%", 0.10)):
            r = [rows[(s, b)] for s in seeds if (s, b) in rows and rows[(s, b)]["ia"] < thr and rows[(s, b)]["it"] < thr]
            if len(r) < 4:
                L.append(f"| {b} ({lab}) | {len(r)} | too few | | |"); continue
            kd = [x["kd"] for x in r]; ed = [x["ed"] for x in r]; ck, ce = boot_mean(kd), boot_mean(ed)
            L.append(f"| {b} ({lab}) | {len(r)} | {np.mean(kd):+.1f} [{ck[0]:+.1f}, {ck[1]:+.1f}] | {np.mean(ed):+.2f} [{ce[0]:+.2f}, {ce[1]:+.2f}] | "
                     f"{np.mean([x['ia'] for x in r]):.3f} / {np.mean([x['it'] for x in r]):.3f} |")
    L += ["", "| branch | regression: intercept (key damage pp at equal idle) [95% CI] | slope pp per unit idle gap [95% CI] | seeds |", "|---|---|---|---|"]
    for b in S["branches"]:
        r = [rows[(s, b)] for s in seeds if (s, b) in rows]
        bb, ci0, ci1 = intercept([x["kd"] for x in r], [x["it"] - x["ia"] for x in r])
        L.append(f"| {b} | {bb[0]:+.1f} [{ci0[0]:+.1f}, {ci0[1]:+.1f}] | {bb[1]:+.1f} [{ci1[0]:+.1f}, {ci1[1]:+.1f}] | {len(r)} |")
    if arm == "U":
        L += ["", "**Bribe-only vs lie-only (extra defections), restricted to seeds where bribe-only, lie-only and their shared twin are all below the threshold:**", "",
              "| subset | seeds | bribe-only | lie-only | diff [95% CI] | two-sided p |", "|---|---|---|---|---|---|"]
        B, Lb = "method=insider_bribe_only", "method=insider_lie_only"
        for lab, thr in (("all", 9), ("< median", med), ("< 10%", 0.10)):
            ss = [s for s in seeds if (s, B) in rows and (s, Lb) in rows and max(rows[(s, B)]["ia"], rows[(s, Lb)]["ia"], rows[(s, B)]["it"]) < thr]
            if len(ss) < 4: L.append(f"| {lab} | {len(ss)} | too few | | | |"); continue
            d = np.array([rows[(s, B)]["ed"] - rows[(s, Lb)]["ed"] for s in ss]); c = boot_mean(d)
            L.append(f"| {lab} | {len(ss)} | {np.mean([rows[(s, B)]['ed'] for s in ss]):+.2f} | {np.mean([rows[(s, Lb)]['ed'] for s in ss]):+.2f} | "
                     f"{d.mean():+.2f} [{c[0]:+.2f}, {c[1]:+.2f}] | {signflip(d):.2g} |")
        r = [s for s in seeds if (s, B) in rows and (s, Lb) in rows]
        d = [rows[(s, B)]["ed"] - rows[(s, Lb)]["ed"] for s in r]; x = [rows[(s, Lb)]["ia"] - rows[(s, B)]["ia"] for s in r]
        bb, ci0, ci1 = intercept(d, x)
        L += ["", f"Regression of (bribe-only − lie-only) extra defections on (lie-only idle − bribe-only idle): intercept {bb[0]:+.2f} "
              f"[{ci0[0]:+.2f}, {ci0[1]:+.2f}], slope {bb[1]:+.2f} [{ci1[0]:+.2f}, {ci1[1]:+.2f}], {len(r)} seeds."]
    L.append("")
open(f"{O}/timeout_sensitivity.md", "w").write("\n".join(L)); print("\n".join(L))
